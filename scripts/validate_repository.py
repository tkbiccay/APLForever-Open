#!/usr/bin/env python3
"""Validate APLForever catalogue and preserved revision integrity."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


EXPECTED_ROLES = (
    ("Druid", "Balance", "DPS"), ("Druid", "Feral", "DPS"),
    ("Druid", "Guardian", "Tank"), ("Druid", "Restoration", "Healer"),
    ("Hunter", "BeastMastery", "DPS"), ("Hunter", "Marksmanship", "DPS"),
    ("Hunter", "Survival", "DPS"),
    ("Mage", "Arcane", "DPS"), ("Mage", "Fire", "DPS"), ("Mage", "Frost", "DPS"),
    ("Paladin", "Holy", "Healer"), ("Paladin", "Protection", "Tank"),
    ("Paladin", "Retribution", "DPS"),
    ("Priest", "Discipline", "Healer"), ("Priest", "Holy", "Healer"),
    ("Priest", "Shadow", "DPS"),
    ("Rogue", "Assassination", "DPS"), ("Rogue", "Combat", "DPS"),
    ("Rogue", "Subtlety", "DPS"),
    ("Shaman", "Elemental", "DPS"), ("Shaman", "Enhancement", "DPS"),
    ("Shaman", "Restoration", "Healer"),
    ("Warlock", "Affliction", "DPS"), ("Warlock", "Demonology", "DPS"),
    ("Warlock", "Destruction", "DPS"),
    ("Warrior", "Arms", "DPS"), ("Warrior", "Fury", "DPS"),
    ("Warrior", "Protection", "Tank"),
)
SUPPORT_STATUSES = {"Supported", "Partial", "Experimental", "Blocked", "Unknown"}
LIFECYCLE_STATUSES = {
    "Default", "Draft", "StaticValidated", "PendingInGame", "InGameValidated",
    "Approved", "ReportedWorking", "NeedsRetest", "Retired", "Unknown",
}
ROLE_REFERENCES = ("preferred_apl", "last_working_apl", "last_approved_apl", "shipped_default_apl")
REVISION_RE = re.compile(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\Z")
HASH_RE = re.compile(r"[0-9a-f]{64}\Z")
# New canonical APL filenames use Class_Spec; role stays in the catalogue.
APL_NAME_RE = re.compile(
    r"APL_(?P<class>[A-Z][A-Za-z0-9]*)_(?P<spec>[A-Z][A-Za-z0-9]*)_"
    r"(?P<revision>v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))_"
    r"(?P<status>Default|Draft|StaticValidated|PendingInGame|InGameValidated|Approved|ReportedWorking|NeedsRetest|Retired)\.txt\Z"
)
# Exact pre-policy files remain immutable as explicit, checked legacy revisions.
LEGACY_APL_NAME_RE = re.compile(
    r"APL_(?P<class>[A-Z][A-Za-z0-9]*)_(?P<spec>[A-Z][A-Za-z0-9]*)_"
    r"(?P<role>DPS|Tank|Healer)_(?P<revision>v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))_"
    r"(?P<status>Default|Draft|StaticValidated|PendingInGame|InGameValidated|Approved|ReportedWorking|NeedsRetest|Retired)\.txt\Z"
)


def _read_catalogue(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8-sig") as handle:
        data = json.load(handle)
    if not isinstance(data, dict) or not isinstance(data.get("roles"), list):
        raise ValueError("catalogue must be an object containing a roles array")
    return data


def _role_key(role: dict[str, Any]) -> tuple[str, str, str]:
    return (role.get("class", ""), role.get("spec", ""), role.get("role", ""))


def render_catalogue(data: dict[str, Any]) -> str:
    """Render the concise role catalogue deterministically from roles.json."""
    rows = [
        "# APLForever role catalogue", "",
        "Generated from `catalogue/roles.json`; do not edit this file directly.", "",
        "| APL name | Class | Spec | Role | Support | Validation | Preferred APL | Latest revision |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for role in data["roles"]:
        if not isinstance(role, dict):
            rows.append("| INVALID | — | — | — | — | — | — | — |")
            continue
        preferred = role.get("preferred_apl") or "—"
        latest = role.get("latest_revision") or "—"
        rows.append(
            f"| {role.get('apl_name', '—')} | {role['class']} | {role['spec']} | {role['role']} | "
            f"{role.get('support_status', 'Unknown')} | {role.get('validation_status', 'Unknown')} | "
            f"{preferred} | {latest} |"
        )
    return "\n".join(rows) + "\n"


def _git(root: Path, *args: str) -> subprocess.CompletedProcess[str] | None:
    try:
        return subprocess.run(
            ["git", "-C", str(root), *args], capture_output=True, text=True,
            check=False, timeout=5,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None


def _baseline_catalogue(root: Path) -> tuple[dict[str, Any] | None, str | None, str | None]:
    probe = _git(root, "rev-parse", "--verify", "HEAD")
    if probe is None or probe.returncode != 0:
        return None, None, "no Git baseline available (no HEAD commit or Git executable)"
    base_branch = os.environ.get("GITHUB_BASE_REF") or "main"
    candidate_ref = f"origin/{base_branch}"
    available = _git(root, "rev-parse", "--verify", candidate_ref)
    baseline_ref = "HEAD"
    if available is not None and available.returncode == 0:
        merge_base = _git(root, "merge-base", "HEAD", candidate_ref)
        if merge_base is not None and merge_base.returncode == 0:
            baseline_ref = merge_base.stdout.strip()
    result = _git(root, "show", f"{baseline_ref}:catalogue/roles.json")
    if result is None or result.returncode != 0:
        return None, baseline_ref, f"no prior catalogue baseline available in {baseline_ref}"
    try:
        baseline = json.loads(result.stdout)
        if not isinstance(baseline.get("roles"), list):
            return None, baseline_ref, "prior catalogue baseline is malformed"
        return baseline, baseline_ref, None
    except (json.JSONDecodeError, AttributeError):
        return None, baseline_ref, "prior catalogue baseline is malformed"


def _lifecycle_folder(role: dict[str, Any], revision: dict[str, Any]) -> str:
    """The selected testing profile is Current, not necessarily Approved."""
    selected = role.get("preferred_apl")
    if selected is None:
        latest = role.get("latest_revision")
        selected = next(
            (item.get("apl_file") for item in role.get("revisions", [])
             if item.get("revision") == latest),
            None,
        )
    if revision.get("apl_file") == selected:
        return "Current"
    if (revision.get("apl_file") == role.get("last_working_apl")
            or revision.get("status") in {"ReportedWorking", "Approved"}):
        return "Checkpoints"
    if role.get("preferred_apl") and revision.get("revision") == role.get("latest_revision"):
        return "Candidates"
    return "Archive"


def validate_repository(
    root: Path, *, check_git: bool = True, enforce_layout: bool = True,
) -> tuple[list[str], str | None]:
    """Return validation errors and a baseline-preservation note, if applicable."""
    errors: list[str] = []
    catalogue_path = root / "catalogue" / "roles.json"
    try:
        data = _read_catalogue(catalogue_path)
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        return [f"catalogue/roles.json: {exc}"], None

    if data.get("schema_version") != 1:
        errors.append("catalogue/roles.json: schema_version must be 1")
    role_rows = data["roles"]
    keys = [_role_key(role) if isinstance(role, dict) else ("", "", "") for role in role_rows]
    duplicates = {key for key in keys if keys.count(key) > 1}
    for key in sorted(duplicates):
        errors.append(f"catalogue: duplicate role {key}")
    found = set(keys)
    for missing in sorted(set(EXPECTED_ROLES) - found):
        errors.append(f"catalogue: missing intended role {missing}")
    for extra in sorted(found - set(EXPECTED_ROLES)):
        errors.append(f"catalogue: unexpected role {extra}")
    if len(role_rows) != 28:
        errors.append(f"catalogue: expected exactly 28 roles, found {len(role_rows)}")

    revisions_by_path: dict[str, tuple[dict[str, Any], dict[str, Any]]] = {}
    revisions_by_role: dict[tuple[str, str, str], set[str]] = {}
    for index, role in enumerate(role_rows):
        if not isinstance(role, dict):
            errors.append(f"catalogue: roles[{index}] must be an object")
            continue
        label = "_".join(_role_key(role)) or f"role index {index}"
        for field in ("class", "spec", "role"):
            if not isinstance(role.get(field), str) or not role[field]:
                errors.append(f"{label}: {field} must be a non-empty string")
        expected_apl_name = f"{role.get('class')}_{role.get('spec')}"
        if role.get("apl_name") != expected_apl_name:
            errors.append(f"{label}: apl_name must equal {expected_apl_name!r}")
        if not isinstance(role.get("support_status"), str) or role["support_status"] not in SUPPORT_STATUSES:
            errors.append(f"{label}: invalid or missing support_status")
        if not isinstance(role.get("validation_status"), str) or role["validation_status"] not in LIFECYCLE_STATUSES:
            errors.append(f"{label}: invalid or missing validation_status")
        for field in (*ROLE_REFERENCES, "latest_revision", "limitations", "revisions"):
            if field not in role:
                errors.append(f"{label}: missing {field}")
        if not isinstance(role.get("limitations"), list) or not isinstance(role.get("revisions"), list):
            errors.append(f"{label}: limitations and revisions must be arrays")
            continue
        if not all(isinstance(item, str) for item in role["limitations"]):
            errors.append(f"{label}: limitations entries must be strings")

        role_revisions: dict[str, dict[str, Any]] = {}
        role_paths: dict[str, dict[str, Any]] = {}
        for rev_index, revision in enumerate(role["revisions"]):
            rev_label = f"{label} revision {rev_index}"
            if not isinstance(revision, dict):
                errors.append(f"{rev_label}: must be an object")
                continue
            version = revision.get("revision")
            if not isinstance(version, str) or not REVISION_RE.fullmatch(version):
                errors.append(f"{rev_label}: invalid revision syntax")
            elif version in role_revisions:
                errors.append(f"{rev_label}: duplicate revision {version}")
            else:
                role_revisions[version] = revision
            status = revision.get("status")
            if not isinstance(status, str) or status not in LIFECYCLE_STATUSES - {"Unknown"}:
                errors.append(f"{rev_label}: invalid status")
            path_value = revision.get("apl_file")
            if not isinstance(path_value, str) or not path_value:
                errors.append(f"{rev_label}: apl_file must be a repository-relative path")
                continue
            path = Path(path_value)
            if path.is_absolute() or ".." in path.parts:
                errors.append(f"{rev_label}: apl_file must remain within the repository")
                continue
            legacy = revision.get("legacy_filename") is True
            if legacy:
                match = LEGACY_APL_NAME_RE.fullmatch(path.name)
                expected_name = (
                    f"APL_{role.get('class')}_{role.get('spec')}_{role.get('role')}_"
                    f"{version}_{status}.txt"
                )
            else:
                match = APL_NAME_RE.fullmatch(path.name)
                expected_name = (
                    f"APL_{role.get('class')}_{role.get('spec')}_"
                    f"{version}_{status}.txt"
                )
            expected_dir = f"roles/{role.get('class')}/{_lifecycle_folder(role, revision)}"
            if (path.name != expected_name or not match
                    or (enforce_layout and path.parent.as_posix() != expected_dir)
                    or (not enforce_layout and path.parent.as_posix() not in {"roles", expected_dir})):
                errors.append(f"{rev_label}: non-canonical APL filename/layout {path_value!r}; expected {expected_dir}")
            moved_from = revision.get("relocated_from")
            if moved_from is not None:
                origin = Path(moved_from) if isinstance(moved_from, str) else Path(".")
                prior_dir = origin.parent.parts
                prior_allowed = (prior_dir == ("roles",) or
                                 (len(prior_dir) == 3 and prior_dir[0] == "roles" and
                                  prior_dir[1] == role.get("class") and
                                  prior_dir[2] in {"Current", "Candidates", "Checkpoints", "Archive"}))
                if (not isinstance(moved_from, str) or origin.is_absolute()
                        or ".." in origin.parts or not prior_allowed or origin.name != path.name):
                    errors.append(f"{rev_label}: invalid relocated_from provenance: {moved_from!r}")
            if status == "Approved" and isinstance(revision.get("purity_review"), str) and revision["purity_review"].startswith("Required:"):
                errors.append(f"{rev_label}: APL with unresolved spec/role purity review cannot be Approved")
            if path_value in revisions_by_path:
                errors.append(f"{rev_label}: APL file is assigned to more than one revision")
            revisions_by_path[path_value] = (role, revision)
            role_paths[path_value] = revision
            content_path = root / path
            if not content_path.is_file():
                errors.append(f"{rev_label}: referenced APL file does not exist: {path_value}")
            else:
                content = content_path.read_bytes()
                digest = revision.get("sha256")
                if not isinstance(digest, str) or not HASH_RE.fullmatch(digest):
                    errors.append(f"{rev_label}: sha256 must be a lowercase SHA-256 digest")
                elif hashlib.sha256(content).hexdigest() != digest:
                    errors.append(f"{rev_label}: sha256 mismatch for {path_value}")
                if not content.strip():
                    errors.append(f"{rev_label}: empty APL cannot be catalogued")
                elif re.search(rb"(?im)^\s*(?:placeholder|todo|insert apl|apl goes here)\b", content):
                    errors.append(f"{rev_label}: placeholder content cannot be catalogued")
            evidence = revision.get("evidence", [])
            if not isinstance(evidence, list):
                errors.append(f"{rev_label}: evidence must be an array")
                evidence = []
            if not isinstance(revision.get("test_results", []), list):
                errors.append(f"{rev_label}: test_results must be an array")
            rollback = revision.get("rollback_reference")
            if status == "Approved":
                has_ingame = any(
                    isinstance(item, dict)
                    and item.get("kind") == "in_game"
                    and isinstance(item.get("reference"), str)
                    and item["reference"].strip()
                    for item in evidence
                )
                if role.get("support_status") != "Supported" or not has_ingame:
                    errors.append(f"{rev_label}: Approved requires Supported role and in-game evidence reference")

        revisions_by_role[_role_key(role)] = set(role_revisions)

        for revision in role["revisions"]:
            if not isinstance(revision, dict):
                continue
            rollback = revision.get("rollback_reference")
            if rollback is not None:
                prior = role_paths.get(rollback) if isinstance(rollback, str) else None
                if prior is None or not (root / rollback).is_file():
                    errors.append(f"{label}: rollback_reference does not resolve to an existing revision: {rollback}")

        for field in ROLE_REFERENCES:
            reference = role.get(field)
            if reference is None:
                continue
            if not isinstance(reference, str) or reference not in revisions_by_path:
                # revisions_by_path may include another role, so verify ownership below as well.
                errors.append(f"{label}: {field} does not resolve to a declared revision")
                continue
            owner, revision = revisions_by_path[reference]
            if owner is not role:
                errors.append(f"{label}: {field} points to another role's APL")
            else:
                if not (root / reference).is_file():
                    errors.append(f"{label}: protected reference is missing: {reference}")
                if not revision.get("sha256"):
                    errors.append(f"{label}: protected reference has no content hash: {reference}")
        latest = role.get("latest_revision")
        if latest is not None and (not isinstance(latest, str) or latest not in role_revisions):
            errors.append(f"{label}: latest_revision does not resolve to a declared revision")
        elif role_revisions and latest != max(role_revisions, key=lambda item: tuple(int(part) for part in item[1:].split("."))):
            errors.append(f"{label}: latest_revision must identify the highest declared revision")
        for field, expected_status in (("last_approved_apl", "Approved"), ("shipped_default_apl", "Default")):
            reference = role.get(field)
            if isinstance(reference, str):
                pair = revisions_by_path.get(reference)
                if pair and pair[0] is role and pair[1].get("status") != expected_status:
                    errors.append(f"{label}: {field} must reference a {expected_status} revision")
        if role.get("validation_status") == "Approved":
            preferred = role.get("preferred_apl")
            owned = revisions_by_path.get(preferred) if preferred else None
            if not owned or owned[0] is not role or owned[1].get("status") != "Approved":
                errors.append(f"{label}: Approved validation requires an Approved preferred APL")

    # Every APL in roles/ must be declared in the catalogue; undeclared historical files are errors.
    roles_dir = root / "roles"
    if roles_dir.exists():
        for file_path in roles_dir.rglob("*.txt"):
            rel = file_path.relative_to(root).as_posix()
            if rel not in revisions_by_path:
                errors.append(f"roles: undeclared APL file {rel}")

    # Supporting filenames, when supplied, must follow their canonical role association.
    support_patterns = (
        re.compile(
            r"(?:Research|Tests)_(?P<stem>[A-Z][A-Za-z0-9]*_[A-Z][A-Za-z0-9]*)_"
            r"(?P<revision>v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))\.md\Z"
        ),
        re.compile(r"(?:Changelog|Limitations)_(?P<stem>[A-Z][A-Za-z0-9]*_[A-Z][A-Za-z0-9]*)\.md\Z"),
    )
    if roles_dir.exists():
        expected_stems = {f"{klass}_{spec}" for klass, spec, _ in EXPECTED_ROLES}
        revisions_by_stem = {
            f"{klass}_{spec}": revisions_by_role.get((klass, spec, role), set())
            for klass, spec, role in EXPECTED_ROLES
        }
        for file_path in roles_dir.rglob("*.md"):
            match = next((pattern.fullmatch(file_path.name) for pattern in support_patterns if pattern.fullmatch(file_path.name)), None)
            if not match or match.group("stem") not in expected_stems:
                errors.append(f"roles: non-canonical supporting filename {file_path.relative_to(root).as_posix()}")
            elif "revision" in match.groupdict():
                if match.group("revision") not in revisions_by_stem.get(match.group("stem"), set()):
                    errors.append(
                        f"roles: supporting-file revision has no matching APL revision: "
                        f"{file_path.relative_to(root).as_posix()}"
                    )

    baseline_note = None
    if check_git:
        baseline, baseline_ref, baseline_note = _baseline_catalogue(root)
        if baseline is not None:
            current_roles = {_role_key(r): r for r in data["roles"] if isinstance(r, dict)}
            for old_role in baseline["roles"]:
                if not isinstance(old_role, dict):
                    continue
                current_role = current_roles.get(_role_key(old_role))
                if current_role is None:
                    continue  # Missing roles were reported above.
                new_revisions = {r.get("revision"): r for r in current_role.get("revisions", [])
                                 if isinstance(r, dict)}
                for prior in old_role.get("revisions", []):
                    if not isinstance(prior, dict):
                        continue
                    prior_path = prior.get("apl_file")
                    revision = new_revisions.get(prior.get("revision"))
                    if not isinstance(prior_path, str) or revision is None:
                        errors.append(f"Git baseline: protected revision removed: {prior_path}")
                        continue
                    current_path = revision.get("apl_file")
                    if not isinstance(current_path, str):
                        errors.append(f"Git baseline: protected APL path missing: {prior_path}")
                        continue
                    if current_path != prior_path:
                        # One explicit path-only migration: same role, revision,
                        # basename, catalogue SHA-256 and original Git blob.
                        if (revision.get("relocated_from") != prior_path
                                or Path(current_path).name != Path(prior_path).name
                                or revision.get("sha256") != prior.get("sha256")):
                            errors.append(f"Git baseline: unverified relocation of protected APL: {prior_path}")
                            continue
                    prior_blob = _git(root, "rev-parse", f"{baseline_ref}:{prior_path}")
                    if prior_blob is None or prior_blob.returncode != 0:
                        errors.append(f"Git baseline: protected APL missing from {baseline_ref}: {prior_path}")
                    elif not (root / current_path).is_file():
                        errors.append(f"Git baseline: protected APL removed from working tree: {prior_path}")
                    else:
                        current_blob = _git(root, "hash-object", "--", current_path)
                        if (current_blob is None or current_blob.returncode != 0
                                or current_blob.stdout.strip() != prior_blob.stdout.strip()):
                            errors.append(f"Git baseline: protected APL changed in place since {baseline_ref}: {prior_path}; add a new revision")

    generated_path = root / "Catalogue_All_Roles.md"
    try:
        if not generated_path.is_file() or generated_path.read_text(encoding="utf-8-sig") != render_catalogue(data):
            errors.append("Catalogue_All_Roles.md is missing or stale; regenerate it with --write-catalogue")
    except OSError as exc:
        errors.append(f"Catalogue_All_Roles.md: {exc}")
    return errors, baseline_note


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--write-catalogue", action="store_true", help="regenerate Catalogue_All_Roles.md")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        data = _read_catalogue(root / "catalogue" / "roles.json")
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"FAIL: catalogue/roles.json: {exc}", file=sys.stderr)
        return 1
    if args.write_catalogue:
        (root / "Catalogue_All_Roles.md").write_text(render_catalogue(data), encoding="utf-8", newline="\n")
    errors, baseline_note = validate_repository(root)
    if baseline_note:
        print(f"INFO: {baseline_note}")
    if errors:
        for error in errors:
            print(f"FAIL: {error}", file=sys.stderr)
        return 1
    print(f"OK: {len(data['roles'])} intended roles; catalogue references, filenames, hashes, and protections checked.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
